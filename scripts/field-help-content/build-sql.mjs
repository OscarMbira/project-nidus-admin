#!/usr/bin/env node
/**
 * Admin field help (Admin rule 23) — build an idempotent seed SQL file for admin.field_help from a content module.
 *   node scripts/field-help-content/build-sql.mjs <content.mjs> <SQL/vNNN_name.sql> "<header title>"
 * The module exports MODULE (module_code) and ROWS: [help_key, title, purpose, examples[], format_notes?, extra_notes?].
 * Refuses keys not starting with "admin.", duplicate keys, and the word "into" (Supabase SQL editor trap).
 * Same contract as the monorepo builder (scripts/field-help-content/build-sql.mjs), Admin schema.
 */
import fs from 'node:fs'
import path from 'node:path'
import { pathToFileURL } from 'node:url'

const q = (v) => (v == null || v === '' ? 'NULL' : `'${String(v).replace(/'/g, "''")}'`)

export function buildSql({ module, rows, title }) {
  const seen = new Set()
  for (const [key, , purpose, examples, fmt, extra] of rows) {
    if (!/^admin\.[a-z0-9_]+\.[a-z0-9_]+$/.test(key)) throw new Error(`Bad key: ${key}`)
    if (seen.has(key)) throw new Error(`Duplicate key: ${key}`)
    seen.add(key)
    if (!purpose || !examples?.length) throw new Error(`Purpose and example required: ${key}`)
    const text = [purpose, ...(examples || []), fmt, extra].filter(Boolean).join(' ')
    if (/\binto\b/i.test(text)) throw new Error(`Avoid the word "into" (SQL editor trap): ${key}`)
  }
  const values = rows.map(([key, t, purpose, examples, fmt, extra]) => `  (${q(key)}, ${q(t)}, ${q(purpose)}, ${q(examples.join('\n'))}, ${q(fmt)}, ${q(extra)}, ${q(module)})`)
  return `-- ============================================================================
-- ${title}
-- Admin field-level help (Admin rule 23; monorepo v1345 slice 6). Generated by
-- scripts/field-help-content/build-sql.mjs — edit the content module, not this file. Idempotent.
-- Prerequisite: v250_admin_field_help.sql.
-- ============================================================================

INSERT INTO admin.field_help (help_key, title, purpose, examples, format_notes, extra_notes, module_code)
VALUES
${values.join(',\n')}
ON CONFLICT (help_key, form_key, locale) DO UPDATE SET
  title = EXCLUDED.title, purpose = EXCLUDED.purpose, examples = EXCLUDED.examples,
  format_notes = EXCLUDED.format_notes, extra_notes = EXCLUDED.extra_notes,
  module_code = EXCLUDED.module_code, is_active = TRUE, updated_at = NOW();

-- Check: rows for this module
SELECT module_code, COUNT(*) AS help_rows FROM admin.field_help WHERE module_code = ${q(module)} GROUP BY module_code;
`
}

if (process.argv[1] && path.resolve(process.argv[1]) === path.resolve(new URL(import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, '$1'))) {
  const [contentPath, outPath, title] = process.argv.slice(2)
  const mod = await import(pathToFileURL(path.resolve(contentPath)).href)
  fs.writeFileSync(outPath, buildSql({ module: mod.MODULE, rows: mod.ROWS, title }))
  console.log(`Wrote ${outPath}: ${mod.ROWS.length} entries`)
}
